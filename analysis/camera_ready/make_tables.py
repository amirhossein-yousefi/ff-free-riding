#!/usr/bin/env python3
"""Generate the camera-ready LaTeX tables from results/*.json. Never hand-type numbers.

Run:  python analysis/make_tables.py        (from CR; writes paper/tables/*.tex)

Every file starts with a provenance line naming its source JSONs. Conventions:
  * mean +- SAMPLE SD over seeds (ddof=1), 2 dp unless stated;
  * paired deltas / CIs come from the 5000-resample paired bootstraps in results/;
  * in the merged dissociation table the Range row is computed from the UNROUNDED means
    (verifier fix: the submitted Table 3 used the printed 2-dp means, which gave an S2-TTA
    range of 0.27 pp instead of 0.28 pp); probe / ladder spans are of unrounded means too.
Tables use booktabs only.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import config as C  # noqa: E402

PROT = list(C.PROTOCOLS)
SEEDS = [str(s) for s in C.SEEDS]
OUT = C.TABLES


def J(name):
    return json.load(open(C.RESULTS / f"{name}.json"))


def header(sources):
    srcs = ", ".join(f"results/{s}.json" for s in sources)
    return f"% AUTO-GENERATED by analysis/make_tables.py from {srcs} — do not hand-edit\n"


def write(name, sources, body):
    p = OUT / f"{name}.tex"
    with open(p, "w") as f:
        f.write(header(sources))
        f.write(body.rstrip() + "\n")
    print(f"wrote paper/tables/{name}.tex")


# ----------------------------------------------------------------------------- formatting
def num(x, nd=2):
    return f"{x:.{nd}f}"


def pm(agg, nd=2, sdnd=None):
    sdnd = nd if sdnd is None else sdnd
    return f"${agg['mean']:.{nd}f}\\!\\pm\\!{agg['sd']:.{sdnd}f}$"


def sg(x, nd=2):
    return f"${x:+.{nd}f}$"


def ci(pooled, nd=2, key_d="delta_pp"):
    d, (lo, hi) = pooled[key_d], pooled["ci95_pp"]
    return f"${d:+.{nd}f}$\\,[${lo:+.{nd}f}$,\\,${hi:+.{nd}f}$]"


def pm1(pooled_list):
    """'Yes' if every CI lies inside (-1, +1) pp, else 'No (<protocols>)'."""
    bad = [p for p, q in pooled_list if not q["within_pm1pp"]]
    return "Yes" if not bad else "\\begin{tabular}[t]{@{}l@{}}No (" + ",\\\\".join(bad) + ")\\end{tabular}"


