def t_ladder():
    L = J("readout_ladder")
    V = ("gamma0", "gated_k0", "cumulative")
    PV = L["per_variant"]
    labels = {"R0": "R0: plain goodness sum (deployed)",
              "R1": "R1: per-depth weights $w_d$",
              "R2": "R2: per-depth temperatures ($w_d{>}0$)",
              "R3": "R3: margin-gated $w_d(x)$"}
    rows = []
    for R in ("R0", "R1", "R2", "R3"):
        cells = [labels[R]]
        for v in V:
            a = PV[v]["eval_acc_pp"][R]
            c = pm(a)
            if R != "R0":
                gnn = PV[v]["gain_vs_R0_pp"][R]
                c += f" (${gnn['mean']:+.2f}\\!\\pm\\!{gnn['sd']:.2f}$)"
            cells.append(c)
        cells.append(num(L["trio_span_pp_per_rung"][R]))
        rows.append(" & ".join(cells) + " \\\\")
    dg = L["differential_gain_R1"]
    rows.append("\\midrule")
